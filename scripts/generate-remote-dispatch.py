"""Generate an explicit typed allowlist from the desktop's command registry.
No reflection or dynamic invocation exists in the deployed server.
"""
from pathlib import Path
import re
root = Path(__file__).resolve().parent.parent
native = root/'apps/desktop/src-tauri/src'
registry = (native/'lib.rs').read_text()
commands = re.findall(r'commands::(\w+)::(\w+),', registry[registry.index('.invoke_handler'):])
excluded = {'workspace_pick','reveal_in_finder','attachment_pick','save_text_file','artifacts_export','skill_import_pick','provider_login_start','provider_login_cancel','open_external','open_in_editor','confirm_dialog','app_quit','app_hide_to_tray','session_subscribe','terminal_subscribe'}
arms=[]
def split_params(raw):
    parts=[]; start=0; depth=0
    for i,ch in enumerate(raw):
        if ch in '<([{': depth+=1
        elif ch in '>)]}': depth-=1
        elif ch==',' and depth==0: parts.append(raw[start:i].strip());start=i+1
    if raw[start:].strip():parts.append(raw[start:].strip())
    return parts
for module,name in commands:
    if name in excluded: continue
    source=(native/'commands'/f'{module}.rs').read_text()
    match=re.search(r'pub\s+(async\s+)?fn\s+'+name+r'\s*\((.*?)\)\s*(?:->\s*(.*?))?\s*\{',source,re.S)
    if not match: raise ValueError(name)
    expressions=[]
    for param in split_params(match[2]):
        arg,typ=param.split(':',1);arg=arg.strip();typ=typ.strip()
        if 'State<' in typ: expressions.append('app.state::<AppState>()')
        elif 'AppHandle' in typ: expressions.append('app.clone()')
        elif 'Channel<' in typ: raise ValueError('unhandled channel '+name)
        else:
            camel=re.sub(r'_([a-z])',lambda m:m[1].upper(),arg)
            expressions.append(f'decode(args["{camel}"].clone())?')
    call=f'commands::{module}::{name}('+', '.join(expressions)+')'
    if match[1]: call+='.await'
    if match[3] and ('CommandResult<' in match[3] or 'Result<' in match[3]):call+='?'
    arms.append(f'        "{name}" => encode({call}),')
text='''// Generated by scripts/generate-remote-dispatch.py; explicit reviewed allowlist.
use crate::{commands, state::AppState};
use serde::{Serialize, de::DeserializeOwned};
use serde_json::Value;
use tauri::Manager;
use thingmaker_supervisor::DesktopError;
fn decode<T: DeserializeOwned>(value: Value) -> Result<T, DesktopError> {
    serde_json::from_value(value).map_err(|_| DesktopError::io("Invalid remote command arguments"))
}
fn encode<T: Serialize>(value: T) -> Result<Value, DesktopError> {
    serde_json::to_value(value).map_err(|_| DesktopError::io("Could not encode command response"))
}
pub async fn dispatch(app: &tauri::AppHandle, command: &str, args: Value) -> Result<Value, DesktopError> {
    if command == "session_submit" {
        let id = args["request"]["requestId"].as_str().unwrap_or_default();
        if uuid::Uuid::parse_str(id).is_err() { return Err(DesktopError::io("Invalid request UUID")); }
    }
    match command {
'''+ '\n'.join(arms)+'''
        _ => Err(DesktopError::unsupported("This action requires the desktop or Android file picker")),
    }
}
'''
(native/'remote_dispatch.rs').write_text(text)
print(f'Generated {len(arms)} explicit commands; {len(excluded)} native-only or streamed actions handled separately.')
